#!/usr/bin/env python3
"""DeepInfer's AIME 2026 / GPQA Diamond protocol, run over the teacher's OpenAI-compatible API.

Prompt construction, answer extraction, the rule judge and Pass@k are DeepInfer's own code.
They are vendored unmodified under scripts/vendor/deepinfer_eval (deepseek-ai/DeepInfer
@ 774ce24, Apache-2.0; see NOTICE.md there).

Only the transport differs. DeepInfer uses its offline engine; here each rollout is one
streamed /v1/chat/completions request with
chat_template_kwargs={"enable_thinking": true, "reasoning_effort": <low|high|max|1-100>}.
Before any rollout, a preflight checks (via /tokenize) that the server renders exactly the
prompt the checkpoint's encoding.py would.

Built for a shared teacher (MAX_NUM_SEQS=2, ~40 tok/s at c=1):
  * Small by default: --limit 3 items, --n-sample 1, concurrency 1.
  * Hard budgets:
    - --budget-tokens: completion tokens generated by this invocation.
    - --budget-seconds: wall clock, idle waits included.
    A rollout that would cross either budget is aborted, recorded as `budget`, never scored,
    and redone by the next invocation.
  * Idle gate. A rollout starts only after --idle-quiet-s without a foreign request on the
    engine (running/waiting gauges, the prompt-token counter) and none through the repl proxy
    for --proxy-quiet-s. With --yield (the default), an in-flight rollout is aborted as soon as
    a foreign request shows up, and redone later.
  * Resumable. raw.jsonl is append-only, with one row per attempt. Rerunning with the same
    --out-dir skips every (task, effort, sample) that already finished, and refuses if the
    protocol (data, model, sampling, max_len) changed.

    python3 scripts/deepinfer_bench.py run --bench aime --data-file aime_2026.jsonl \\
        --out-dir RUN --efforts 75,100 --limit 3 --n-sample 1 --dry-run
    python3 scripts/deepinfer_bench.py run ...      # same arguments without --dry-run; rerun to resume
    python3 scripts/deepinfer_bench.py score --out-dir RUN
    python3 scripts/effort_ab_paired.py RUN/paired.jsonl --efforts 75,100

See docs/deepinfer-bench-protocol.md for usage, deviations from DeepInfer and wall-clock.
"""
