def iso_ts(text: str) -> float:
    return datetime.fromisoformat(text.replace("Z", "+00:00")).timestamp()


# --------------------------------------------------------------------------- idle gate
@dataclass
class Metrics:
    running: int
    waiting: int
    prompt_tokens: int


def parse_metrics(text: str) -> Metrics:
    """vLLM /metrics: request gauges and the prompt-token counter, summed over engines."""
    values = {"vllm:num_requests_running{": 0.0, "vllm:num_requests_waiting{": 0.0,
              "vllm:prompt_tokens_total{": 0.0}
    for line in text.splitlines():
        for prefix in values:
            if line.startswith(prefix):
                values[prefix] += float(line.rsplit(" ", 1)[1])
    running, waiting, prompt = values.values()
    return Metrics(int(running), int(waiting), int(prompt))


class ForeignDetector:
    """Is anyone but us using the engine?

    Two signals, because the gauges are only sampled every --poll-s:
      * running + waiting > our requests in flight;
      * the prompt-token counter grew by more than our own prompts, which catches a short
        request that came and went between two polls. Every request has prompt tokens, but an
        aborted one does not count in request_success_total on this build, so that counter is
        not used. Our prompt is credited when we send it; a credit the engine never consumes
        masks at most one prompt's worth (~100-300 tokens) of foreign traffic.
    """

    def __init__(self) -> None:
        self.prev: int | None = None
        self.credit = 0

    def expect_prompt(self, tokens: int) -> None:
        self.credit += tokens

    def update(self, m: Metrics, ours: int) -> str:
        reason = ""
        if m.running + m.waiting > ours:
            reason = f"engine running={m.running} waiting={m.waiting}, ours={ours}"
        if self.prev is not None:
            delta = m.prompt_tokens - self.prev
            excess = delta - self.credit
            self.credit = max(0, self.credit - delta)
            if excess > 0 and not reason:
                reason = f"{excess} foreign prompt tokens since the last poll"
        self.prev = m.prompt_tokens
        return reason


def proxy_last_activity(db_path: str, base: str, now: float, horizon_s: float = 6 * 3600) -> float | None:
    """Latest start/end of a repl-proxy request to this upstream (epoch s), or None.

    The proxy writes a row when a request ends, so this sees finished requests only. The
    engine gauges cover in-flight ones; this covers the gaps of a live agent session between
    turns (tool calls, a user typing), which the gauges cannot see.

    The proxy's own prefix keepalives (call_origin 'keepalive': 1 output token every ~6 min per
    idle session) are not live sessions and are ignored; counting them kept the gate shut.
    """
    since = datetime.fromtimestamp(now - horizon_s, timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.000Z")
    con = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True, timeout=2)
    try:
        columns = {row[1] for row in con.execute("PRAGMA table_info(requests)")}
        not_keepalive = " AND call_origin != 'keepalive'" if "call_origin" in columns else ""
        rows = con.execute("SELECT started_at, ended_at, upstream FROM requests WHERE started_at >= ?"
                           + not_keepalive, (since,)).fetchall()
    finally:
        con.close()
    target = base.rstrip("/")
    stamps = [iso_ts(ts) for started, ended, upstream in rows if (upstream or "").rstrip("/") == target
              for ts in (started, ended) if ts]
    return max(stamps) if stamps else None


# --------------------------------------------------------------------------- transport
def http_json(base: str, path: str, body: dict[str, Any] | None = None, timeout: float = 30) -> Any:
    data = None if body is None else json.dumps(body).encode()
    req = urllib.request.Request(base.rstrip("/") + path, data, {"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as f:
        raw = f.read().decode()
    return raw if path == "/metrics" else json.loads(raw)


class Rollout(threading.Thread):
    """One streamed chat completion; abort() closes the socket, which makes vLLM drop it."""

    def __init__(self, base: str, body: dict[str, Any], job: Job, prompt_tokens: int, stall_s: float,
                 over_budget=lambda: False):
        super().__init__(daemon=True)
        self.base, self.body, self.job, self.stall_s = base, body, job, stall_s
        self.over_budget = over_budget  # checked after every chunk: the token budget is hard
        self.prompt_tokens = prompt_tokens
        self.tokens = 0
        self.reasoning: list[str] = []
        self.content: list[str] = []
        self.finish_reason: str | None = None
        self.usage: dict[str, Any] = {}
        self.error = ""
        self.abort_reason = ""
        self.started_at = utc_now()
        self.t0 = time.monotonic()
        self.ttft: float | None = None
        self.elapsed = 0.0
        self.conn: http.client.HTTPConnection | None = None
        self.lock = threading.Lock()

    def abort(self, reason: str) -> None:
        with self.lock:
            if self.abort_reason:
                return
            self.abort_reason = reason
            sock = self.conn.sock if self.conn else None
        if sock is not None:
            try:
                sock.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass

    def run(self) -> None:
        try:
            self._stream()
        except Exception as exc:  # noqa: BLE001 - recorded on the row; aborts land here too
            self.error = f"{type(exc).__name__}: {exc}"[:300]
        finally:
            self.elapsed = time.monotonic() - self.t0
            if self.conn:
                self.conn.close()

    def _stream(self) -> None:
        url = urllib.parse.urlsplit(self.base)
        cls = http.client.HTTPSConnection if url.scheme == "https" else http.client.HTTPConnection
        with self.lock:
            if self.abort_reason:
                return
            self.conn = cls(url.hostname, url.port, timeout=self.stall_s)
        self.conn.request("POST", url.path.rstrip("/") + "/v1/chat/completions", json.dumps(self.body),
                          {"Content-Type": "application/json", "Accept": "text/event-stream"})
        resp = self.conn.getresponse()
        if resp.status != 200:
            raise RuntimeError(f"HTTP {resp.status}: {resp.read()[:200]!r}")
        while True:
            line = resp.readline()
            if not line:
                break
            line = line.strip()
            if not line.startswith(b"data:"):
                continue
            payload = line[5:].strip()
            if payload == b"[DONE]":
                break
            chunk = json.loads(payload)
            if chunk.get("usage"):
                self.usage = chunk["usage"]
                self.tokens = int(self.usage.get("completion_tokens") or 0)
                if self.over_budget():
                    with self.lock:
                        self.abort_reason = self.abort_reason or "budget"
                    return
            for choice in chunk.get("choices") or []:
                delta = choice.get("delta") or {}
                reasoning = delta.get("reasoning") or delta.get("reasoning_content")
                if reasoning:
                    self.reasoning.append(reasoning)
                if delta.get("content"):
                    self.content.append(delta["content"])
                if (reasoning or delta.get("content")) and self.ttft is None:
                    self.ttft = time.monotonic() - self.t0
                if choice.get("finish_reason"):
                    self.finish_reason = choice["finish_reason"]

    def row(self) -> dict[str, Any]:
        job = self.job
        if self.abort_reason:
            status = self.abort_reason
        elif self.finish_reason and not self.error:
            status = "done"
        else:
            status = "error"
            self.error = self.error or "stream ended without a finish_reason"
        details = self.usage.get("completion_tokens_details") or {}
        row = {"task_id": job.task_id, "effort": job.effort, "effort_label": job.label,
               "sample_idx": job.sample_idx, "seed": job.seed, "status": status,
               "finish_reason": self.finish_reason,
               "prompt_tokens": int(self.usage.get("prompt_tokens") or self.prompt_tokens),
               "completion_tokens": self.tokens, "reasoning_tokens": details.get("reasoning_tokens"),
               "elapsed_s": round(self.elapsed, 2),
               "ttft_s": None if self.ttft is None else round(self.ttft, 2),
               "started_at": self.started_at,
               "reasoning": "".join(self.reasoning), "content": "".join(self.content)}
        if status == "error":
            row["error"] = self.error
        return row


