# --------------------------------------------------------------------------- protocol
def parse_effort(value: Any) -> int | str:
    """DeepInfer run_eval.py --reasoning-effort: an integer 1-100, or one of low/high/max."""
    text = str(value).strip()
    if text in EFFORT_LEVELS:
        return text
    try:
        effort = int(text)
    except ValueError:
        raise ValueError(f"expected an integer 1-100 or one of {tuple(EFFORT_LEVELS)}, got {value!r}") from None
    if not 1 <= effort <= 100:
        raise ValueError(f"expected 1-100, got {effort}")
    return effort


def effort_budget(effort: int | str) -> int:
    """The number the prompt carries; an arm is identified by it ("high" and 75 are one arm)."""
    return EFFORT_LEVELS[effort] if isinstance(effort, str) else effort


def load_records(bench_name: str, data_file: str | os.PathLike, *, limit: int | None = None,
                 offset: int = 0, task_ids: list[str] | None = None) -> list[dict[str, Any]]:
    """DeepInfer's bench.load + bench.build_records, then the subset to run."""
    bench = load_bench(bench_name)
    records = bench.build_records(bench.load(data_file))
    if task_ids:
        by_id = {r["task_id"]: r for r in records}
        unknown = [t for t in task_ids if t not in by_id]
        if unknown:
            raise SystemExit(f"task ids not in {data_file}: {unknown[:5]}")
        return [by_id[t] for t in task_ids]
    records = records[offset:]
    return records[:limit] if limit else records


def build_request(record: dict[str, Any], effort: int | str, *, model: str, prompt_tokens: int,
                  seed: int, max_len: int = MAX_LEN, temperature: float = 1.0,
                  top_p: float = 1.0) -> dict[str, Any]:
    """One rollout. max_tokens = max_len - prompt_len, at least 1, as in run_eval.py."""
    return {
        "model": model,
        "messages": record["messages"],
        "temperature": temperature,
        "top_p": top_p,
        "max_tokens": max(max_len - prompt_tokens, 1),
        "seed": seed,
        "skip_special_tokens": False,  # DeepInfer decodes with skip_special_tokens=False
        "stream": True,
        "stream_options": {"include_usage": True, "continuous_usage_stats": True},
        "chat_template_kwargs": {"enable_thinking": True, "reasoning_effort": effort},
    }


def check_rendered_prompt(rendered: str, messages: list[dict[str, Any]], effort: int | str,
                          reference: str | None = None) -> list[str]:
    """Problems with the server-rendered prompt; [] when it is DeepInfer's prompt."""
    problems = []
    if reference is not None and rendered != reference:
        problems.append("differs from the checkpoint encoding.py rendering")
    budget = effort_budget(effort)
    budgets = [part.split(" ", 1)[0] for part in rendered.split("Reasoning Effort: ")[1:]]
    if budgets != [str(budget)]:
        problems.append(f"effort line renders {budgets or 'nothing'}, expected [{budget}]")
    if not rendered.endswith("<｜Assistant｜><think>"):
        problems.append("does not end in <｜Assistant｜><think> (thinking off?)")
    if messages[-1]["content"] not in rendered:
        problems.append("user content missing")
    return problems


def rollout_raw_text(reasoning: str | None, content: str | None, finish_reason: str | None) -> str:
    """The text DeepInfer decodes: the prompt ends in <think>, so thinking, </think>, answer.

    The endpoint splits the two; </think> was emitted iff an answer started (or the rollout
    stopped naturally). A rollout cut inside its thinking has no </think>, so DeepInfer's
    fallbacks scan its tail, as they would offline.
    """
    reasoning, content = reasoning or "", content or ""
    if content or finish_reason == "stop":
        return reasoning + "</think>" + content
    return reasoning


def score_rollout(bench_name: str, row: dict[str, Any], record: dict[str, Any]) -> dict[str, Any]:
    """DeepInfer's rule judge (bench.score_rollout) on one endpoint rollout."""
    raw_text = rollout_raw_text(row.get("reasoning"), row.get("content"), row.get("finish_reason"))
    scored = load_bench(bench_name).score_rollout(dict(row, raw_text=raw_text), record)
    scored.pop("raw_text")
    scored["blacklisted_tokens"] = [t for t in BLACKLIST_TOKENS if t in raw_text]
    return scored


# --------------------------------------------------------------------------- statistics
def mcnemar_exact(b: int, c: int) -> float:
    """Exact two-sided McNemar (binomial) p for b vs c discordant pairs."""
    n = b + c
    if n == 0:
        return 1.0
    tail = sum(math.comb(n, i) for i in range(min(b, c) + 1)) / 2 ** n
    return min(1.0, 2 * tail)


def sign_flip_p(diffs: list[float], *, exact_max: int = 16, draws: int = 20000, seed: int = 0) -> float:
    """Two-sided paired permutation p over items: flip the sign of each per-item difference.

    Items, not rollouts, are the unit: samples of one item share its difficulty, so treating
    them as independent pairs (as McNemar does) overstates the evidence.
    """
    nz = [d for d in diffs if d != 0]
    if not nz:
        return 1.0
    obs = abs(sum(nz)) - 1e-12
    if len(nz) <= exact_max:
        hits = sum(abs(sum(s * d for s, d in zip(signs, nz))) >= obs
                   for signs in itertools.product((1, -1), repeat=len(nz)))
        return hits / 2 ** len(nz)
    rng = random.Random(seed)
    hits = sum(abs(sum(d if rng.random() < 0.5 else -d for d in nz)) >= obs for _ in range(draws))
    return (hits + 1) / (draws + 1)


def bootstrap_ci(values: list[float], *, seed: int = 0, draws: int = 10000,
                 alpha: float = 0.05) -> tuple[float | None, float | None]:
    """Percentile bootstrap CI of the mean, resampling items."""
    if not values:
        return None, None
    rng = random.Random(seed)
    n = len(values)
    means = sorted(sum(values[rng.randrange(n)] for _ in range(n)) / n for _ in range(draws))
    return means[int(alpha / 2 * draws)], means[int((1 - alpha / 2) * draws) - 1]


def _per_item_accuracy(rows: list[dict[str, Any]]) -> dict[str, float]:
    flags: dict[str, list[bool]] = defaultdict(list)
    for row in rows:
        flags[row["task_id"]].append(bool(row["correct"]))
    return {task: sum(f) / len(f) for task, f in flags.items()}


def compare_arms(scored: list[dict[str, Any]], a: int, b: int) -> dict[str, Any]:
    """Arm b minus arm a, over the items both arms have rollouts for."""
    acc_a = _per_item_accuracy([r for r in scored if r["effort"] == a])
    acc_b = _per_item_accuracy([r for r in scored if r["effort"] == b])
    items = sorted(set(acc_a) & set(acc_b))
    diff = {t: acc_b[t] - acc_a[t] for t in items}
    by_key = {(r["task_id"], r["effort"], r["sample_idx"]): bool(r["correct"]) for r in scored}
    pairs = sorted((t, s) for (t, e, s) in by_key if e == a and (t, b, s) in by_key)
    a_only = [[t, s] for t, s in pairs if by_key[(t, a, s)] and not by_key[(t, b, s)]]
    b_only = [[t, s] for t, s in pairs if by_key[(t, b, s)] and not by_key[(t, a, s)]]
    lo, hi = bootstrap_ci(list(diff.values()))
    return {
        "items": len(items),
        "pairs": len(pairs),
        f"pass1_{a}": statistics.mean(acc_a[t] for t in items) if items else None,
        f"pass1_{b}": statistics.mean(acc_b[t] for t in items) if items else None,
        "mean_diff": statistics.mean(diff.values()) if items else None,
        "ci95_items": [lo, hi],
        "sign_flip_p": sign_flip_p(list(diff.values())),
        "per_item_diff": diff,
        "discordant": {f"{a}_only": a_only, f"{b}_only": b_only},
        "mcnemar_p": mcnemar_exact(len(a_only), len(b_only)),
    }


