def _pct(x: float | None) -> str:
    return "  n/a" if x is None else f"{100 * x:5.1f}"


def summarize_arm(rows: list[dict[str, Any]], *, effort: int, task_ids: list[str], n_sample: int,
                  attempts: Counter) -> dict[str, Any]:
    pk = passk()
    summary = pk.summarize(rows, n_sample=n_sample, k_list=pk.default_k_list(n_sample))
    acc = _per_item_accuracy(rows)
    lo, hi = bootstrap_ci(list(acc.values()))
    finish = Counter(str(r.get("finish_reason")) for r in rows)
    toks = sorted(r.get("completion_tokens") or 0 for r in rows)
    rates = [r["completion_tokens"] / (r["elapsed_s"] - (r.get("ttft_s") or 0)) for r in rows
             if r.get("completion_tokens") and r.get("elapsed_s", 0) - (r.get("ttft_s") or 0) > 0]
    expected = len(task_ids) * n_sample
    summary.update({
        "effort": effort,
        "expected_rollouts": expected,
        "coverage_complete": len(rows) == expected and set(acc) == set(task_ids),
        "pass1_ci95_items": [lo, hi],
        "finish_reasons": dict(finish),
        "truncated_rollouts": finish.get("length", 0),
        "extract_sources": dict(Counter(str(r.get("extract_source")) for r in rows)),
        "extract_failed": sum(r.get("pred") is None for r in rows) / len(rows),
        "blacklisted_rollouts": sum(bool(r.get("blacklisted_tokens")) for r in rows),
        "completion_tokens": {"mean": statistics.mean(toks), "median": statistics.median(toks),
                              "p90": toks[min(len(toks) - 1, int(0.9 * len(toks)))], "max": toks[-1],
                              "sum": sum(toks)},
        "decode_tok_s_median": statistics.median(rates) if rates else None,
        "wall_s_sum": round(sum(r.get("elapsed_s") or 0 for r in rows), 1),
    })
    for status in ("yielded", "budget", "error", "interrupted"):
        summary[f"{status}_attempts"] = attempts[(effort, status)]
    return summary


def cmd_score(args) -> int:
    out = Path(args.out_dir)
    meta = json.loads((out / "meta.json").read_text())
    bench_name, n_sample, task_ids = meta["bench"], meta["n_sample"], meta["task_ids"]
    data_file = args.data_file or meta["data_file"]
    if sha256_file(data_file) != meta["data_sha256"]:
        raise SystemExit(f"{data_file} is not the file this run was generated from (sha256 differs)")
    by_id = {r["task_id"]: r for r in load_records(bench_name, data_file, task_ids=task_ids)}
    raw = read_jsonl(out / "raw.jsonl")
    final = {(r["task_id"], r["effort"], r["sample_idx"]): r for r in raw
             if r.get("status") == "done" and r["task_id"] in by_id}
    scored = [score_rollout(bench_name, r, by_id[r["task_id"]]) for r in final.values()]
    attempts = Counter((r["effort"], r.get("status")) for r in raw)
    efforts = sorted(set(meta["efforts"]) | {r["effort"] for r in scored})
    arms = {str(e): summarize_arm([r for r in scored if r["effort"] == e], effort=e, task_ids=task_ids,
                                  n_sample=n_sample, attempts=attempts)
            for e in efforts if any(r["effort"] == e for r in scored)}
    comparisons = {f"{a}_vs_{b}": compare_arms(scored, a, b)
                   for a, b in itertools.combinations([int(e) for e in arms], 2)}
    summary = {
        "bench": bench_name, "model": meta["model"], "base": meta["base"], "deepinfer": meta.get("deepinfer"),
        "judge": "rule", "temperature": meta["temperature"], "top_p": meta["top_p"], "max_len": meta["max_len"],
        "n_sample": n_sample, "protocol_n_sample": meta.get("protocol_n_sample"), "planned_tasks": len(task_ids),
        "arms": arms, "comparisons": comparisons,
        "reference": {"deepinfer_readme_pass1": DEEPINFER_REFERENCE_PASS1[bench_name],
                      "note": "DeepInfer eval/README.md section 7, V4.1 under its default configuration "
                              "(every task, aime 32 / gpqa 8 samples, effort 100, max_len 144K, LLM judge, "
                              "DeepInfer engine); indicative, aggregate only"},
        "deviations": meta.get("deviations"),
    }
    with (out / "scored.jsonl").open("w") as fh:
        fh.writelines(json.dumps(r, ensure_ascii=False) + "\n" for r in scored)
    with (out / "paired.jsonl").open("w") as fh:
        fh.writelines(json.dumps(r) + "\n" for r in paired_rows(scored, bench_name))
    (out / "summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False) + "\n")

    print(f"\n{bench_name}  {meta['model']}  rule judge  n_sample {n_sample} (protocol "
          f"{meta.get('protocol_n_sample')})  planned items {len(task_ids)}")
    print(f"{'arm':>4} {'Pass@1':>7} {'95% CI (items)':>15} {'rollouts':>9} {'cut':>4} {'tok mean':>9} "
          f"{'tok p90':>8} {'tok/s':>6} {'yield':>6} {'flag':>5}")
    for key, s in arms.items():
        lo, hi = s["pass1_ci95_items"]
        rate = s["decode_tok_s_median"]
        print(f"{key:>4} {_pct(s['Pass@1']):>7} {_pct(lo):>7}-{_pct(hi):<7} "
              f"{s['num_rollouts']:>4}/{s['expected_rollouts']:<4} {s['truncated_rollouts']:>4} "
              f"{s['completion_tokens']['mean']:>9,.0f} {s['completion_tokens']['p90']:>8,} "
              f"{'n/a' if rate is None else f'{rate:.1f}':>6} {s['yielded_attempts']:>6} {s['blacklisted_rollouts']:>5}")
    for key, c in comparisons.items():
        a, b = key.split("_vs_")
        lo, hi = c["ci95_items"]
        print(f"{b} - {a}: {_pct(c['mean_diff'])} pts over {c['items']} items (95% CI {_pct(lo)} to {_pct(hi)}), "
              f"sign-flip p={c['sign_flip_p']:.3g}; discordant pairs {len(c['discordant'][f'{a}_only'])} "
              f"{a}-only vs {len(c['discordant'][f'{b}_only'])} {b}-only (McNemar p={c['mcnemar_p']:.3g})")
    print(f"reference (DeepInfer README, full protocol): Pass@1 {100 * DEEPINFER_REFERENCE_PASS1[bench_name]:.1f}"
          f"  -- comparable only with every task, n_sample >= {meta.get('protocol_n_sample')}, effort 100, "
          f"no truncation")
    print(f"wrote {out}/scored.jsonl, summary.json, paired.jsonl")
    return 0


