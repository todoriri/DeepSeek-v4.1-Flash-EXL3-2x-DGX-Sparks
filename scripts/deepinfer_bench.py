def _load_vendored(rel: str, name: str) -> ModuleType:
    if name in sys.modules:
        return sys.modules[name]
    if str(VENDOR) not in sys.path:  # bench.py imports `common.io` from its eval/ directory
        sys.path.insert(0, str(VENDOR))
    spec = importlib.util.spec_from_file_location(name, VENDOR / rel)
    assert spec and spec.loader, rel
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


